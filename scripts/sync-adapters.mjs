/** Generate marketplace adapters from distribution/catalog.json. */
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stampSkillProvenance } from './skill-provenance.mjs';
import { codexListingInterface, validateCodexPortalManifest } from './codex-portal-contract.mjs';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const check = process.argv.includes('--check');
const stale = [];
const catalog = JSON.parse(readFileSync(join(root, 'distribution', 'catalog.json'), 'utf8'));
const marketplaces = JSON.parse(readFileSync(join(root, 'distribution', 'marketplaces.json'), 'utf8'));
const codexSubmissions = JSON.parse(readFileSync(join(root, 'distribution', 'codex-submissions.json'), 'utf8'));
const pkg = catalog.package;
const author = {
  name: 'Qodo',
  email: 'support@qodo.ai',
  url: 'https://www.qodo.ai',
};
const keywords = ['qodo', 'code-review', 'code-intelligence', 'standards', 'coding-agents'];

function provider(id) {
  const value = marketplaces.providers.find((entry) => entry.id === id);
  if (!value) throw new Error(`Unknown marketplace provider: ${id}`);
  return value;
}

function listing(providerId, packageName) {
  const value = provider(providerId).listings.find((entry) => entry.package === packageName);
  if (!value) throw new Error(`${providerId}: no listing for ${packageName}`);
  return value;
}

function writeText(path, content) {
  const target = join(root, path);
  if (check) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      // A missing generated file is stale, just like different content.
    }
    // Git for Windows may materialize tracked text with CRLF even though the
    // generator emits deterministic LF. Freshness is about content, not the
    // checkout's platform-native line endings.
    if (current.replace(/\r\n/g, '\n') !== content) stale.push(path);
    return;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
}

function writeJson(path, value) {
  writeText(path, `${JSON.stringify(value, null, 2)}\n`);
}

for (const skill of catalog.skills) {
  const yaml = [
    '# Generated by scripts/sync-adapters.mjs. Do not edit by hand.',
    'interface:',
    `  display_name: ${JSON.stringify(skill.displayName)}`,
    `  short_description: ${JSON.stringify(skill.shortDescription)}`,
    `  brand_color: ${JSON.stringify(pkg.brandColor)}`,
    `  default_prompt: ${JSON.stringify(skill.defaultPrompt)}`,
    'policy:',
    '  allow_implicit_invocation: true',
    '',
  ].join('\n');
  const target = join(root, 'skills', skill.name, 'agents', 'openai.yaml');
  writeText(relative(root, target).split(sep).join('/'), yaml);
}

function collectFiles(dir, prefix = '') {
  if (!existsSync(dir)) return [];
  const files = [];
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    const relativePath = prefix ? `${prefix}/${name}` : name;
    const stat = lstatSync(path);
    if (stat.isSymbolicLink()) throw new Error(`${path}: generated adapters may not contain symlinks`);
    if (stat.isDirectory()) files.push(...collectFiles(path, relativePath));
    else if (stat.isFile()) files.push(relativePath);
  }
  return files;
}

function installPackage(name) {
  const value = catalog.installPackages.find((entry) => entry.name === name);
  if (!value) throw new Error(`Unknown install package: ${name}`);
  return value;
}

function pluginManifest(value) {
  return {
    $schema: 'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json',
    name: value.name,
    version: pkg.version,
    description: value.description,
    author,
    homepage: pkg.homepage,
    repository: pkg.repository,
    license: pkg.license,
    keywords,
  };
}

function codexManifest(value) {
  return {
    name: value.name,
    version: pkg.version,
    description: value.description,
    author,
    homepage: pkg.homepage,
    repository: pkg.repository,
    license: pkg.license,
    keywords,
    skills: './skills/',
    interface: {
      displayName: value.displayName,
      ...codexListingInterface(catalog, codexSubmissions.listings.find((entry) => entry.package === value.name)),
      longDescription: value.description,
      developerName: author.name,
      category: 'Developer Tools',
      capabilities: value.skills.map((name) => catalog.skills.find((skill) => skill.name === name).displayName),
      websiteURL: pkg.homepage,
      privacyPolicyURL: pkg.privacyPolicyUrl,
      termsOfServiceURL: pkg.termsOfServiceUrl,
      brandColor: pkg.brandColor,
      composerIcon: './assets/qodo.png',
      logo: './assets/qodo.png',
    },
  };
}

function kiroReadPermissionProfile() {
  const command = catalog.runtime.command;
  const readCommand = catalog.runtime.readCommand;
  if (typeof readCommand !== 'string' || !readCommand.startsWith(`${command} `)) {
    throw new Error('runtime.readCommand must be a child of runtime.command');
  }
  const readSuffix = readCommand.slice(command.length);
  const executables = [command, '~/.qodo/bin/qodo', '$QODO_HOME/bin/qodo'];
  const patterns = executables.flatMap((executable) => [
    `${executable} --version`,
    `${executable}${readSuffix} *`,
  ]);
  return [
    '# Generated by scripts/sync-adapters.mjs. Do not edit by hand.',
    '# This template is never applied automatically. The user owns Kiro permissions.',
    'rules:',
    '  - capability: shell',
    '    effect: allow',
    '    match:',
    ...patterns.map((pattern) => `      - ${JSON.stringify(pattern)}`),
    '',
  ].join('\n');
}

function generatedPackageFiles(value, adapterSet = 'claude') {
  const files = new Map([
    ['plugin.json', `${JSON.stringify(pluginManifest(value), null, 2)}\n`],
  ]);
  if (adapterSet === 'codex') {
    const manifest = codexManifest(value);
    files.set('assets/qodo.png', readFileSync(join(root, 'distribution', 'assets', 'codex', 'qodo.png')));
    validateCodexPortalManifest(manifest, (path) => files.get(path));
    files.set('.codex-plugin/plugin.json', `${JSON.stringify(manifest, null, 2)}\n`);
  } else if (adapterSet === 'claude') {
    files.set('.claude-plugin/plugin.json', `${JSON.stringify({
      name: listing('claude', value.name).id,
      version: pkg.version,
      description: value.description,
      author,
      homepage: pkg.homepage,
      repository: pkg.repository,
      license: pkg.license,
      keywords,
    }, null, 2)}\n`);
  } else {
    files.set('README.md', [
      ...(value.name === pkg.name
        ? [
          '<p align="center">',
          '  <img src="./Qodo-Kiro.png" alt="Qodo for Kiro — Qodo AI code review and governance in Kiro" width="840">',
          '</p>',
          '',
        ]
        : []),
      `# ${value.displayName} for Kiro`,
      '',
      'Generated skills contain the complete reviewed Qodo playbooks for this release.',
      `Install or update ${value.displayName} through the Kiro Powers marketplace.`,
      'The Qodo CLI remains a separate runtime and is never bundled here.',
      '',
      '## Optional read-only permission',
      '',
      `The stable \`${catalog.runtime.readCommand} ...\` gateway exposes only tools that the live Qodo catalog`,
      'explicitly marks non-mutating. To remove repeated safe-read prompts, choose **Always allow**',
      `for the exact \`${catalog.runtime.readCommand} *\` pattern in Kiro, or review and merge`,
      '`qodo-read-only.permissions.yaml` into your user- or workspace-scoped Kiro permissions.',
      'Keep every other Qodo command on ask. The Power never changes permission files itself.',
      '',
      `- Privacy: ${pkg.privacyPolicyUrl}`,
      `- Support: ${pkg.supportUrl}`,
      `- Terms: ${pkg.termsOfServiceUrl}`,
      '',
    ].join('\n'));
    files.set('qodo-read-only.permissions.yaml', kiroReadPermissionProfile());
    if (value.name === pkg.name) {
      files.set(
        'Qodo-Kiro.png',
        readFileSync(join(root, 'distribution', 'assets', 'kiro', 'Qodo-Kiro.png')),
      );
    }
  }
  for (const skillName of value.skills) {
    const sourceRoot = join(root, 'skills', skillName);
    const skill = catalog.skills.find((entry) => entry.name === skillName);
    const distribution = adapterSet === 'kiro' ? 'kiro-power' : 'marketplace';
    const host = adapterSet === 'kiro' ? 'kiro' : adapterSet === 'codex' ? 'codex' : 'claude-code';
    for (const path of collectFiles(sourceRoot)) {
      const content = readFileSync(join(sourceRoot, path), 'utf8');
      files.set(
        `skills/${skillName}/${path}`,
        path === 'SKILL.md'
          ? stampSkillProvenance(content, {
            name: skillName,
            version: skill.version,
            packageName: value.name,
            distribution,
            host,
          })
          : content,
      );
    }
  }
  // Preserve the earlier marketplace invocation as a compatibility alias while the canonical skill name
  // moves from qodo-pr-resolver to qodo-review-resolver. This is generated from
  // the canonical workflow (never separately authored), and its narrow
  // description prevents it competing with the canonical skill for new tasks.
  if (value.name === pkg.name) {
    const canonical = files.get('skills/qodo-review-resolver/SKILL.md');
    if (!canonical) throw new Error(`${value.name}: missing qodo-review-resolver compatibility source`);
    const compatibilityAlias = canonical
      .replace(/^name:\s*qodo-review-resolver$/m, 'name: qodo-pr-resolver')
      .replace(
        /^description:.*$/m,
        'description: Compatibility alias for explicit qodo-pr-resolver requests. Follow the complete Qodo PR review workflow embedded here and use qodo-review-resolver for new invocations; lifecycle update provenance intentionally uses the canonical qodo-review-resolver release-index identity.',
      )
      .replace(/^metadata:$/m, 'metadata:\n  alias_for: "qodo-review-resolver"');
    files.set('skills/qodo-pr-resolver/SKILL.md', compatibilityAlias);
    if (adapterSet === 'codex') {
      const canonicalAdapter = files.get('skills/qodo-review-resolver/agents/openai.yaml');
      if (!canonicalAdapter) throw new Error(`${value.name}: missing qodo-review-resolver Codex adapter`);
      if (!/^  allow_implicit_invocation: true$/m.test(canonicalAdapter)) {
        throw new Error(`${value.name}: qodo-review-resolver Codex adapter must declare implicit invocation`);
      }
      files.set(
        'skills/qodo-pr-resolver/agents/openai.yaml',
        canonicalAdapter
          .replace(/\$qodo-review-resolver\b/g, '$qodo-pr-resolver')
          .replace(/^  allow_implicit_invocation: true$/m, '  allow_implicit_invocation: false'),
      );
    }
  }
  return files;
}

function generatedContentMatches(path, expected) {
  try {
    if (Buffer.isBuffer(expected)) return readFileSync(path).equals(expected);
    const current = readFileSync(path, 'utf8');
    return current.replace(/\r\n/g, '\n') === expected.replace(/\r\n/g, '\n');
  } catch {
    return false;
  }
}

function syncGeneratedDirectory(relativeRoot, files) {
  const targetRoot = join(root, relativeRoot);
  if (check) {
    const actual = collectFiles(targetRoot).sort();
    const expected = [...files.keys()].sort();
    if (JSON.stringify(actual) !== JSON.stringify(expected)) stale.push(`${relativeRoot}/`);
    for (const [path, content] of files) {
      if (!generatedContentMatches(join(targetRoot, path), content)) {
        stale.push(`${relativeRoot}/${path}`);
      }
    }
    return;
  }
  rmSync(targetRoot, { recursive: true, force: true });
  for (const [path, content] of files) {
    const target = join(targetRoot, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
}

const legacyAtomicRoots = [
  'plugin.json',
  '.codex-plugin/plugin.json',
  '.claude-plugin/plugin.json',
  'gemini-extension.json',
];
for (const path of legacyAtomicRoots) {
  if (check && existsSync(join(root, path))) stale.push(`${path} (unsafe all-skills package)`);
  if (!check) rmSync(join(root, path), { force: true });
}

writeJson('.agents/plugins/marketplace.json', {
  name: 'qodo',
  interface: { displayName: 'Qodo' },
  plugins: catalog.installPackages.map((value) => ({
    name: value.name,
    source: { source: 'local', path: `./codex-packages/${value.name}` },
    policy: { installation: 'AVAILABLE', authentication: 'ON_USE' },
    category: 'Developer Tools',
  })),
});

writeJson('.claude-plugin/marketplace.json', {
  name: 'qodo',
  owner: author,
  metadata: { description: pkg.description, version: pkg.version },
  plugins: catalog.installPackages.map((value) => ({
    name: listing('claude', value.name).id,
    source: `./packages/${value.name}`,
    description: value.description,
    author,
    homepage: pkg.homepage,
    repository: pkg.repository,
    license: pkg.license,
    keywords,
  })),
});

for (const value of catalog.installPackages) {
  syncGeneratedDirectory(`packages/${value.name}`, generatedPackageFiles(value, 'claude'));
  syncGeneratedDirectory(`codex-packages/${value.name}`, generatedPackageFiles(value, 'codex'));
}

// Keep the existing Kiro core source path stable. Optional capabilities are a
// separate Power, because Kiro installs a Power atomically.
syncGeneratedDirectory('kiro-power', generatedPackageFiles(installPackage(pkg.name), 'kiro'));
syncGeneratedDirectory(
  'kiro-power-standards',
  generatedPackageFiles(installPackage('qodo-standards'), 'kiro'),
);

if (stale.length) {
  console.error(`Generated adapters are stale: ${stale.join(', ')}`);
  process.exit(1);
}
console.log(
  check
    ? `Adapters are current for ${catalog.skills.length} skills at package ${pkg.version}.`
    : `Generated adapters for ${catalog.skills.length} skills at package ${pkg.version}.`,
);
