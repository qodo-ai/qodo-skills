/** Generate marketplace adapters from distribution/catalog.json. */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const check = process.argv.includes('--check');
const stale = [];
const catalog = JSON.parse(readFileSync(join(root, 'distribution', 'catalog.json'), 'utf8'));
const pkg = catalog.package;
const author = {
  name: 'Qodo',
  email: 'support@qodo.ai',
  url: 'https://www.qodo.ai',
};
const keywords = ['qodo', 'code-review', 'code-intelligence', 'standards', 'coding-agents'];

function writeText(path, content) {
  const target = join(root, path);
  if (check) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      // A missing generated file is stale, just like different content.
    }
    if (current !== content) stale.push(path);
    return;
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, content);
}

function writeJson(path, value) {
  writeText(path, `${JSON.stringify(value, null, 2)}\n`);
}

writeJson('plugin.json', {
  $schema: 'https://agent-plugins.org/schemas/1.0.0/plugin.schema.json',
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
  author,
  homepage: pkg.homepage,
  repository: pkg.repository,
  license: pkg.license,
  keywords,
});

writeJson('.codex-plugin/plugin.json', {
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
  author,
  homepage: pkg.homepage,
  repository: pkg.repository,
  license: pkg.license,
  keywords,
  skills: './skills/',
  interface: {
    displayName: pkg.displayName,
    shortDescription: 'Qodo intelligence and reviews in your coding agent.',
    longDescription: pkg.description,
    developerName: author.name,
    category: 'Developer Tools',
    capabilities: ['Code intelligence', 'Code review', 'Organizational standards'],
    websiteURL: pkg.homepage,
    brandColor: pkg.brandColor,
    defaultPrompt: [
      'Set up Qodo in this coding agent.',
      'Review my local changes with Qodo.',
      'Load the Qodo standards for this task.',
    ],
  },
});

writeJson('.agents/plugins/marketplace.json', {
  name: 'qodo',
  interface: { displayName: 'Qodo' },
  plugins: [
    {
      name: pkg.name,
      source: { source: 'local', path: './' },
      policy: { installation: 'AVAILABLE', authentication: 'ON_USE' },
      category: 'Developer Tools',
    },
  ],
});

writeJson('.claude-plugin/plugin.json', {
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
  author,
  homepage: pkg.homepage,
  repository: pkg.repository,
  license: pkg.license,
  keywords,
});

writeJson('.claude-plugin/marketplace.json', {
  name: 'qodo',
  owner: author,
  metadata: { description: pkg.description, version: pkg.version },
  plugins: [
    {
      name: pkg.name,
      source: './',
      description: pkg.description,
      version: pkg.version,
      author,
      homepage: pkg.homepage,
      repository: pkg.repository,
      license: pkg.license,
      keywords,
    },
  ],
});

writeJson('gemini-extension.json', {
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
});

for (const skill of catalog.skills) {
  const yaml = [
    '# Generated by scripts/sync-adapters.mjs. Do not edit by hand.',
    'interface:',
    `  display_name: ${JSON.stringify(skill.displayName)}`,
    `  short_description: ${JSON.stringify(skill.shortDescription)}`,
    `  brand_color: ${JSON.stringify(pkg.brandColor)}`,
    `  default_prompt: ${JSON.stringify(skill.defaultPrompt)}`,
    'policy:',
    '  allow_implicit_invocation: true',
    '',
  ].join('\n');
  const target = join(root, 'skills', skill.name, 'agents', 'openai.yaml');
  writeText(relative(root, target), yaml);
}

if (stale.length) {
  console.error(`Generated adapters are stale: ${stale.join(', ')}`);
  process.exit(1);
}
console.log(
  check
    ? `Adapters are current for ${catalog.skills.length} skills at package ${pkg.version}.`
    : `Generated adapters for ${catalog.skills.length} skills at package ${pkg.version}.`,
);
